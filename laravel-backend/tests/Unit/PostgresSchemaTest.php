<?php

namespace Tests\Unit;

use App\Migration\PostgresSchema;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

class PostgresSchemaTest extends TestCase
{
    private function column(array $overrides = []): array
    {
        return array_replace(['COLUMN_NAME' => 'flag', 'DATA_TYPE' => 'tinyint', 'COLUMN_TYPE' => 'tinyint(1)',
            'IS_NULLABLE' => 'NO', 'COLUMN_DEFAULT' => '0', 'EXTRA' => '', 'GENERATION_EXPRESSION' => '',
            'CHARACTER_MAXIMUM_LENGTH' => null, 'NUMERIC_PRECISION' => 3, 'NUMERIC_SCALE' => 0], $overrides);
    }

    public function test_mysql_flags_remain_integer_compatible(): void
    {
        $this->assertSame('"flag" smallint NOT NULL DEFAULT \'0\'', PostgresSchema::column($this->column()));
    }

    public function test_legacy_mixed_case_identity_is_preserved(): void
    {
        $sql = PostgresSchema::column($this->column(['COLUMN_NAME' => 'Bus_ID', 'DATA_TYPE' => 'int', 'COLUMN_TYPE' => 'int unsigned', 'EXTRA' => 'auto_increment']));
        $this->assertSame('"Bus_ID" bigint GENERATED BY DEFAULT AS IDENTITY', $sql);
    }

    public function test_enum_values_and_timestamp_defaults_are_converted(): void
    {
        $enum = PostgresSchema::column($this->column(['COLUMN_NAME' => 'status', 'DATA_TYPE' => 'enum',
            'COLUMN_TYPE' => "enum('active','resolved','seen')", 'COLUMN_DEFAULT' => "'active'"]));
        $this->assertStringContainsString("DEFAULT 'active'", $enum);
        $this->assertStringContainsString("'active','resolved','seen','cleared'", $enum);
        $timestamp = PostgresSchema::column($this->column(['DATA_TYPE' => 'timestamp', 'COLUMN_TYPE' => 'timestamp', 'COLUMN_DEFAULT' => 'current_timestamp()']));
        $this->assertStringContainsString('DEFAULT CURRENT_TIMESTAMP', $timestamp);
    }

    public function test_generated_columns_fail_instead_of_losing_behavior(): void
    {
        $this->expectException(InvalidArgumentException::class);
        PostgresSchema::column($this->column(['GENERATION_EXPRESSION' => 'other + 1']));
    }

    public function test_legacy_empty_enum_values_are_allowed_only_when_detected(): void
    {
        $column = $this->column(['DATA_TYPE' => 'enum', 'COLUMN_TYPE' => "enum('active','seen')", 'COLUMN_DEFAULT' => 'active']);
        $this->assertStringNotContainsString(",'')", PostgresSchema::column($column));
        $column['ENUM_ALLOW_EMPTY'] = true;
        $this->assertStringContainsString(",'')", PostgresSchema::column($column));
    }

    public function test_cross_database_row_digest_preserves_precision_and_nulls(): void
    {
        $columns = [
            $this->column(['COLUMN_NAME' => 'amount', 'DATA_TYPE' => 'decimal']),
            $this->column(['COLUMN_NAME' => 'flag']),
            $this->column(['COLUMN_NAME' => 'missing', 'DATA_TYPE' => 'text']),
            $this->column(['COLUMN_NAME' => 'data', 'DATA_TYPE' => 'json']),
        ];
        $mysql = ['amount' => '12345678901234567890.5000', 'flag' => '1', 'missing' => null, 'data' => '{"z":1,"a":2}'];
        $postgres = ['amount' => '12345678901234567890.50', 'flag' => 1, 'missing' => null, 'data' => '{"a":2,"z":1}'];
        $this->assertSame(PostgresSchema::digest($mysql, $columns), PostgresSchema::digest($postgres, $columns));
        $postgres['missing'] = '';
        $this->assertNotSame(PostgresSchema::digest($mysql, $columns), PostgresSchema::digest($postgres, $columns));
    }

    public function test_blob_snapshot_encoding_round_trips(): void
    {
        $columns = [$this->column(['COLUMN_NAME' => 'payload', 'DATA_TYPE' => 'blob'])];
        $value = "\0\xff\x01binary";
        $this->assertSame(PostgresSchema::digest(['payload' => base64_encode($value)], $columns),
            PostgresSchema::digest(['payload' => $value], $columns, false));
    }
}
