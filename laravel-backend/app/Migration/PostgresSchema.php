<?php

namespace App\Migration;

use InvalidArgumentException;

/** Builds a new PostgreSQL schema from inspected MySQL metadata, without DROP statements. */
final class PostgresSchema
{
    public static function quote(string $name): string
    {
        return '"'.str_replace('"', '""', $name).'"';
    }

    public static function type(array $column): string
    {
        $type = strtolower($column['DATA_TYPE']);
        $unsigned = str_contains($column['COLUMN_TYPE'], 'unsigned');
        return match ($type) {
            // Preserve 0/1 flags as integers: existing queries compare them with 0 and 1.
            'tinyint' => 'smallint',
            'smallint' => $unsigned ? 'integer' : 'smallint',
            'mediumint', 'int', 'integer' => $unsigned ? 'bigint' : 'integer',
            // Identity keys and their foreign keys must share the same integer type.
            // Values outside PostgreSQL's signed bigint range fail the transaction.
            'bigint' => 'bigint',
            'decimal', 'numeric' => 'numeric('.(int) $column['NUMERIC_PRECISION'].','.(int) $column['NUMERIC_SCALE'].')',
            'float', 'double', 'real' => 'double precision',
            'varchar', 'char' => 'varchar('.(int) $column['CHARACTER_MAXIMUM_LENGTH'].')',
            'enum', 'tinytext', 'text', 'mediumtext', 'longtext' => 'text',
            'json' => 'jsonb',
            'date' => 'date',
            'datetime', 'timestamp' => 'timestamp without time zone',
            'time' => 'time without time zone',
            'year' => 'smallint',
            'binary', 'varbinary', 'tinyblob', 'blob', 'mediumblob', 'longblob' => 'bytea',
            default => throw new InvalidArgumentException('Unsupported MySQL type '.$column['COLUMN_TYPE'].' on '.$column['COLUMN_NAME']),
        };
    }

    public static function column(array $column): string
    {
        if (!empty($column['GENERATION_EXPRESSION'])) {
            throw new InvalidArgumentException('Generated columns require manual conversion: '.$column['COLUMN_NAME']);
        }
        $sql = self::quote($column['COLUMN_NAME']).' '.self::type($column);
        if (str_contains($column['EXTRA'], 'auto_increment')) {
            return $sql.' GENERATED BY DEFAULT AS IDENTITY';
        }
        if ($column['IS_NULLABLE'] === 'NO') $sql .= ' NOT NULL';
        $default = $column['COLUMN_DEFAULT'];
        // MariaDB reports SQL literal quotes in COLUMN_DEFAULT; MySQL reports raw values.
        if ($default !== null && strtoupper((string) $default) !== 'NULL') {
            if (preg_match('/^current_timestamp(?:\(\d*\))?$/i', $default)) {
                $sql .= ' DEFAULT CURRENT_TIMESTAMP';
            } else {
                if (strlen($default) >= 2 && $default[0] === "'" && substr($default, -1) === "'") {
                    $default = str_replace("''", "'", substr($default, 1, -1));
                    $default = stripcslashes($default);
                } elseif (str_contains($column['EXTRA'], 'DEFAULT_GENERATED')) {
                    throw new InvalidArgumentException('Expression default needs review: '.$column['COLUMN_NAME']);
                }
                $sql .= " DEFAULT '".str_replace("'", "''", (string) $default)."'";
            }
        }
        if (strtolower($column['DATA_TYPE']) === 'enum') {
            $values = str_getcsv(substr($column['COLUMN_TYPE'], 5, -1), ',', "'", '\\');
            // MySQL non-strict legacy inserts can contain the enum zero-value ''.
            // Permit it only when the inspected snapshot actually contains it.
            if (!empty($column['ENUM_ALLOW_EMPTY']) && !in_array('', $values, true)) $values[] = '';
            if ($column['COLUMN_NAME'] === 'status' && in_array('seen', $values, true) && !in_array('cleared', $values, true)) {
                $values[] = 'cleared';
            }
            $values = array_map(fn ($v) => "'".str_replace("'", "''", $v)."'", $values);
            $sql .= ' CHECK ('.self::quote($column['COLUMN_NAME']).' IN ('.implode(',', $values).'))';
        }
        return $sql;
    }

    public static function binary(array $column): bool
    {
        return in_array(strtolower($column['DATA_TYPE']), ['binary', 'varbinary', 'tinyblob', 'blob', 'mediumblob', 'longblob'], true);
    }

    /** Order-independent row digest, with MySQL/PostgreSQL representation differences normalized. */
    public static function digest(array $row, array $columns, bool $encodedBinary = true): string
    {
        $values = [];
        foreach ($columns as $column) {
            $value = $row[$column['COLUMN_NAME']];
            if (is_resource($value)) $value = stream_get_contents($value);
            if ($value !== null) {
                if (self::binary($column)) {
                    $value = $encodedBinary ? $value : base64_encode($value);
                } elseif (in_array(strtolower($column['DATA_TYPE']), ['decimal', 'numeric', 'float', 'double', 'real'], true)) {
                    // Floating values are normalized to 12 significant digits across drivers.
                    $value = in_array($column['DATA_TYPE'], ['float', 'double', 'real'], true)
                        ? sprintf('%.12g', (float) $value)
                        : (str_contains((string) $value, '.') ? rtrim(rtrim((string) $value, '0'), '.') : (string) $value);
                    if ($value === '-0') $value = '0';
                } elseif (in_array($column['DATA_TYPE'], ['datetime', 'timestamp', 'time'], true)) {
                    $value = preg_replace('/\.0+$/', '', (string) $value);
                    $value = preg_replace('/(\.\d*?[1-9])0+$/', '$1', $value);
                } elseif ($column['DATA_TYPE'] === 'json') {
                    $value = json_encode(self::sortJson(json_decode($value, true, 512, JSON_THROW_ON_ERROR)), JSON_THROW_ON_ERROR);
                } else {
                    $value = (string) $value;
                }
            }
            $values[] = $value;
        }
        return hash('sha256', json_encode($values, JSON_THROW_ON_ERROR), true);
    }

    private static function sortJson(mixed $value): mixed
    {
        if (!is_array($value)) return $value;
        if (!array_is_list($value)) ksort($value);
        return array_map(self::sortJson(...), $value);
    }
}
